#!/usr/bin/env python3
"""Build the two deliverables from src/, demo/ and vendor/.

  public/                 static site for Cloudflare Pages (or any static host)
    index.html            the app; libraries from ./vendor/, CSP pinned in _headers
    _headers              security headers incl. a CSP hash of the inline script
    vendor/               KaTeX and JSZip, served from the same origin
    licenses/             license texts and notices for everything served
  dist/claude-artifact.html   single file for publishing as a claude.ai artifact
                              (libraries from cdnjs, which the artifact sandbox allows)

Usage: python3 tools/build.py      (no dependencies beyond the Python standard library)
"""
import base64, hashlib, json, pathlib, re, shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC, DEMO, VENDOR = ROOT / "src", ROOT / "demo", ROOT / "vendor"
PUBLIC, DIST = ROOT / "public", ROOT / "dist"

KATEX_VER, JSZIP_VER = "0.16.9", "3.10.1"
DEMO_META = json.loads((DEMO / "meta.json").read_text("utf-8"))


def j(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")


def demo_payload():
    files = {p: (DEMO / "lean" / pathlib.Path(p).relative_to("lean")).read_text("utf-8") for p in DEMO_META["files"]}
    return {"label": DEMO_META["label"], "start": DEMO_META["start"], "files": files}


def script_body():
    return "\n" + "\n".join((SRC / f).read_text("utf-8") for f in ("core.js", "glossary.js", "i18n.js", "app.js")) + "\n"


# Bundled demo translations, keyed by the language name used in LANGS (src/i18n.js).
DEMO_LANGS = {"日本語": "ja", "English": "en"}


def demo_translations():
    return {name: json.loads((DEMO / f"translations.{code}.json").read_text("utf-8"))
            for name, code in DEMO_LANGS.items()}


def render(libs, license_links):
    tpl = (SRC / "template.html").read_text("utf-8")
    body = script_body()
    out = (tpl.replace("<!--LIBS-->", libs)
              .replace("<!--LICENSE_LINKS-->", license_links)
              .replace("/*DEMO_DATA*/", j(demo_payload()))
              .replace("/*DEMO_TR*/", j(demo_translations()))
              .replace("<script>\n/*CORE*/\n/*GLOSSARY*/\n/*APP*/\n</script>", "<script>" + body + "</script>"))
    assert "/*" + "APP*/" not in out and out.lower().count("</script") == 5, "template placeholders"
    return out, body


def build_public():
    if PUBLIC.exists():
        shutil.rmtree(PUBLIC)
    (PUBLIC / "vendor").mkdir(parents=True)
    (PUBLIC / "licenses").mkdir()
    shutil.copy(VENDOR / "katex" / "katex.min.js", PUBLIC / "vendor" / "katex.min.js")
    shutil.copy(VENDOR / "jszip" / "jszip.min.js", PUBLIC / "vendor" / "jszip.min.js")
    lic = {
        "LICENSE.txt": ROOT / "LICENSE",
        "NOTICE.txt": ROOT / "NOTICE",
        "CRuby-BSDL.txt": DEMO / "CRuby-BSDL.txt",
        "KaTeX-LICENSE.txt": VENDOR / "katex" / "LICENSE",
        "JSZip-LICENSE.txt": VENDOR / "jszip" / "LICENSE.markdown",
    }
    for name, src in lic.items():
        shutil.copy(src, PUBLIC / "licenses" / name)
    links = ('<a href="licenses/LICENSE.txt">BSD-2-Clause</a> · <a href="licenses/NOTICE.txt">NOTICE</a><br>'
             '<a href="licenses/CRuby-BSDL.txt">CRuby range.c excerpts (BSDL)</a><br>'
             '<a href="licenses/KaTeX-LICENSE.txt">KaTeX (MIT)</a> · <a href="licenses/JSZip-LICENSE.txt">JSZip (MIT)</a>')
    libs = '<script src="vendor/katex.min.js"></script>\n<script src="vendor/jszip.min.js"></script>'
    html, body = render(libs, links)
    (PUBLIC / "index.html").write_text(html, "utf-8")
    digest = base64.b64encode(hashlib.sha256(body.encode("utf-8")).digest()).decode()
    csp = "; ".join([
        "default-src 'none'",
        f"script-src 'self' 'sha256-{digest}'",
        "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
        "font-src https://fonts.gstatic.com",
        "img-src 'self' data:",
        "connect-src https://api.github.com https://api.anthropic.com",
        "base-uri 'none'",
        "form-action 'none'",
        "frame-ancestors 'none'",
    ])
    (PUBLIC / "_headers").write_text(
        "# Generated by tools/build.py. The sha256 pins the inline script of index.html,\n"
        "# and connect-src limits where the page can send anything (keys included).\n"
        "/*\n"
        f"  Content-Security-Policy: {csp}\n"
        "  X-Content-Type-Options: nosniff\n"
        "  Referrer-Policy: no-referrer\n"
        "  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()\n"
        "  Cross-Origin-Opener-Policy: same-origin\n", "utf-8")
    return html


def build_artifact():
    DIST.mkdir(exist_ok=True)
    libs = (f'<script src="https://cdnjs.cloudflare.com/ajax/libs/KaTeX/{KATEX_VER}/katex.min.js"></script>\n'
            f'<script src="https://cdnjs.cloudflare.com/ajax/libs/jszip/{JSZIP_VER}/jszip.min.js"></script>')
    links = ('BSD-2-Clause (© 2026 gotoken)<br>CRuby range.c excerpts: © 1993-2007 Yukihiro Matsumoto, 2-clause BSDL<br>'
             'KaTeX (MIT) · JSZip (MIT)')
    html, _ = render(libs, links)
    (DIST / "claude-artifact.html").write_text(html, "utf-8")


if __name__ == "__main__":
    build_public()
    build_artifact()
    print("built public/ and dist/claude-artifact.html")
